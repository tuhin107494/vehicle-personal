import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { intervalLabel } from "@/lib/billing";
import type { InvoiceT } from "@/lib/types";

const taka = (paisa: number, currency = "BDT") => `${currency} ${(paisa / 100).toLocaleString("en-BD", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const day = (iso: string | null) => (iso ? new Date(iso).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" }) : "-");

/** An A4 invoice built in the browser from the invoice the API returned: who, what period, how much, and whether it is paid. */
export function downloadInvoicePdf(invoice: InvoiceT, platform: string) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  const margin = 16;

  doc.setFont("helvetica", "bold").setFontSize(18).text(platform, margin, 22);
  doc.setFontSize(22).text("INVOICE", width - margin, 22, { align: "right" });
  doc.setFont("helvetica", "normal").setFontSize(10);
  doc.text(invoice.invoice_no, width - margin, 29, { align: "right" });
  doc.text(`Issued: ${day(invoice.created_at)}`, width - margin, 35, { align: "right" });
  doc.text(`Due: ${day(invoice.due_date)}`, width - margin, 41, { align: "right" });

  doc.setFont("helvetica", "bold").text("Billed to", margin, 40);
  doc.setFont("helvetica", "normal");
  const to = [invoice.shop?.name ?? `Shop #${invoice.shop_id}`, invoice.shop?.phone ?? "", invoice.shop?.address ?? ""].filter(Boolean);
  to.forEach((line, i) => doc.text(line, margin, 46 + i * 5.5));

  const status = invoice.status === "paid" ? `PAID on ${day(invoice.paid_at)}` : invoice.status === "void" ? "VOID" : "UNPAID";
  doc.setFont("helvetica", "bold").setFontSize(12).setTextColor(invoice.status === "paid" ? 22 : 180, invoice.status === "paid" ? 120 : 30, 30);
  doc.text(status, width - margin, 50, { align: "right" });
  doc.setTextColor(20);

  autoTable(doc, {
    startY: 68,
    margin: { left: margin, right: margin },
    head: [["Description", "Period", "Amount"]],
    body: [[
      `${invoice.plan?.name ?? "Plan"} subscription (${invoice.plan ? intervalLabel(invoice.plan.billing_interval).toLowerCase() : ""})`,
      `${day(invoice.period_starts_at)} – ${day(invoice.period_ends_at)}`,
      taka(invoice.amount_paisa, invoice.currency),
    ]],
    theme: "grid",
    styles: { font: "helvetica", fontSize: 10, cellPadding: 3, textColor: 20, lineColor: [180, 180, 180], lineWidth: 0.2 },
    headStyles: { fillColor: [235, 235, 235], textColor: 20, fontStyle: "bold" },
    columnStyles: { 2: { halign: "right" } },
  });

  const afterTable = (doc as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 90;
  const rows: [string, string][] = [["Subtotal", taka(invoice.amount_paisa, invoice.currency)]];
  if (invoice.discount_paisa > 0) rows.push([`Discount${invoice.coupon ? ` (${invoice.coupon.code})` : ""}`, `- ${taka(invoice.discount_paisa, invoice.currency)}`]);
  rows.push(["Total", taka(invoice.total_paisa, invoice.currency)]);
  let y = afterTable + 8;
  for (const [label, value] of rows) {
    const bold = label === "Total";
    doc.setFont("helvetica", bold ? "bold" : "normal").setFontSize(bold ? 12 : 10);
    doc.text(label, width - margin - 60, y);
    doc.text(value, width - margin, y, { align: "right" });
    y += bold ? 8 : 6;
  }

  doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(90);
  doc.text("Generated by the dashboard. Amounts are in whole currency units with two decimals.", margin, doc.internal.pageSize.getHeight() - 12);
  doc.save(`${invoice.invoice_no}.pdf`);
}
